from pathlib import Path
import argparse
import simpy
import pandas as pd
import numpy as np


def run_simulation(
    num_patients=100,
    doctors=3,
    nurses=4,
    triage_stations=2,
    lab_technicians=2,
    arrival_interval=5,
    registration_time=4,
    triage_time=7,
    doctor_time=15,
    lab_time=20,
    treatment_time=12,
    lab_probability=0.60,
    seed=42,
    output_dir="outputs",
):
    """
    Simplified Emergency Department patient-flow simulation.

    All times are simulated minutes.
    This is an illustrative model, not a validated clinical model.
    """

    if num_patients < 1:
        raise ValueError("num_patients must be at least 1")

    capacities = {
        "registration": 1,
        "triage": triage_stations,
        "doctor": doctors,
        "laboratory": lab_technicians,
        "treatment": nurses,
    }

    for name, capacity in capacities.items():
        if capacity < 1:
            raise ValueError(f"{name} capacity must be at least 1")

    if arrival_interval <= 0:
        raise ValueError("arrival_interval must be greater than zero")

    service_times = {
        "Registration": registration_time,
        "Triage": triage_time,
        "Doctor Consultation": doctor_time,
        "Laboratory": lab_time,
        "Treatment": treatment_time,
    }

    if any(value <= 0 for value in service_times.values()):
        raise ValueError("All service times must be greater than zero")

    if not 0 <= lab_probability <= 1:
        raise ValueError("lab_probability must be between 0 and 1")

    rng = np.random.default_rng(seed)
    env = simpy.Environment()

    resources = {
        "Registration": simpy.Resource(env, capacity=1),
        "Triage": simpy.Resource(env, capacity=triage_stations),
        "Doctor Consultation": simpy.Resource(env, capacity=doctors),
        "Laboratory": simpy.Resource(env, capacity=lab_technicians),
        "Treatment": simpy.Resource(env, capacity=nurses),
    }

    records = []
    resource_busy_minutes = {name: 0.0 for name in resources}
    queue_waits = {name: [] for name in resources}

    def use_resource(case_id, activity):
        resource = resources[activity]
        service_duration = service_times[activity]

        arrival_at_activity = env.now

        with resource.request() as request:
            yield request

            service_start = env.now
            waiting_time = service_start - arrival_at_activity

            # Simulate service duration.
            yield env.timeout(service_duration)

            service_end = env.now

        queue_waits[activity].append(waiting_time)
        resource_busy_minutes[activity] += service_duration

        records.append({
            "case_id": case_id,
            "activity": activity,
            "queue_entry_time": round(arrival_at_activity, 2),
            "start_time": round(service_start, 2),
            "end_time": round(service_end, 2),
            "waiting_minutes": round(waiting_time, 2),
            "service_minutes": round(service_duration, 2),
        })

    def patient_process(case_id):
        yield from use_resource(case_id, "Registration")
        yield from use_resource(case_id, "Triage")
        yield from use_resource(case_id, "Doctor Consultation")

        # A proportion of patients are sent for laboratory testing.
        if rng.random() < lab_probability:
            yield from use_resource(case_id, "Laboratory")

        yield from use_resource(case_id, "Treatment")

        records.append({
            "case_id": case_id,
            "activity": "Discharge",
            "queue_entry_time": round(env.now, 2),
            "start_time": round(env.now, 2),
            "end_time": round(env.now, 2),
            "waiting_minutes": 0.0,
            "service_minutes": 0.0,
        })

    def arrival_generator():
        for patient_number in range(1, num_patients + 1):
            env.process(patient_process(f"SIM-{patient_number:05d}"))

            if patient_number < num_patients:
                # Exponential arrivals model variable inter-arrival times.
                gap = float(rng.exponential(arrival_interval))
                yield env.timeout(gap)

    env.process(arrival_generator())
    env.run()

    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)

    event_log = pd.DataFrame(records)

    if event_log.empty:
        raise RuntimeError("Simulation generated no events.")

    event_log = event_log.sort_values(
        ["case_id", "start_time"],
        kind="stable"
    ).reset_index(drop=True)

    event_log["timestamp"] = pd.to_datetime(
        event_log["start_time"], unit="m", origin="unix", utc=True
    )

    event_log["sequence"] = (
        event_log.groupby("case_id").cumcount() + 1
    )

    # Event log format compatible with CareFlow process analysis.
    event_log[
        ["case_id", "activity", "timestamp", "sequence"]
    ].to_csv(
        output_path / "simulated_event_log.csv",
        index=False
    )

    # Calculate patient-level journey duration and waiting time.
    case_summary = (
        event_log.groupby("case_id")
        .agg(
            first_event=("start_time", "min"),
            last_event=("end_time", "max"),
            total_waiting_minutes=("waiting_minutes", "sum"),
            total_service_minutes=("service_minutes", "sum"),
            event_count=("activity", "count"),
        )
        .reset_index()
    )

    case_summary["total_journey_minutes"] = (
        case_summary["last_event"] - case_summary["first_event"]
    ).round(2)

    case_summary.to_csv(
        output_path / "simulation_case_summary.csv",
        index=False
    )

    # Resource utilization based on accumulated busy time and
    # the simulation makespan. This is a simplified estimate.
    simulation_end = float(env.now)

    resource_summary = []

    for activity, capacity in {
        "Registration": 1,
        "Triage": triage_stations,
        "Doctor Consultation": doctors,
        "Laboratory": lab_technicians,
        "Treatment": nurses,
    }.items():

        busy = resource_busy_minutes[activity]

        utilization = (
            busy / (capacity * simulation_end) * 100
            if simulation_end > 0 else 0
        )

        resource_summary.append({
            "resource": activity,
            "capacity": capacity,
            "busy_minutes": round(busy, 2),
            "simulation_minutes": round(simulation_end, 2),
            "utilization_percent": round(utilization, 2),
            "average_queue_wait_minutes": round(
                float(np.mean(queue_waits[activity])), 2
            ) if queue_waits[activity] else 0,
        })

    resource_df = pd.DataFrame(resource_summary)

    resource_df.to_csv(
        output_path / "simulation_resource_summary.csv",
        index=False
    )

    metrics = {
        "patients_simulated": int(case_summary["case_id"].nunique()),
        "average_journey_minutes": round(
            float(case_summary["total_journey_minutes"].mean()), 2
        ),
        "average_waiting_minutes": round(
            float(case_summary["total_waiting_minutes"].mean()), 2
        ),
        "average_service_minutes": round(
            float(case_summary["total_service_minutes"].mean()), 2
        ),
        "p90_journey_minutes": round(
            float(case_summary["total_journey_minutes"].quantile(0.90)), 2
        ),
        "simulation_makespan_minutes": round(simulation_end, 2),
    }

    pd.DataFrame([metrics]).to_csv(
        output_path / "simulation_kpis.csv",
        index=False
    )

    print("\nSimulation completed successfully.")
    print(pd.Series(metrics).to_string())
    print("\nFiles saved in:", output_path.resolve())

    return {
        "event_log": event_log,
        "case_summary": case_summary,
        "resource_summary": resource_df,
        "metrics": metrics,
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()

    parser.add_argument("--patients", type=int, default=100)
    parser.add_argument("--doctors", type=int, default=3)
    parser.add_argument("--nurses", type=int, default=4)
    parser.add_argument("--triage-stations", type=int, default=2)
    parser.add_argument("--lab-technicians", type=int, default=2)
    parser.add_argument("--arrival-interval", type=float, default=5)
    parser.add_argument("--seed", type=int, default=42)

    args = parser.parse_args()

    run_simulation(
        num_patients=args.patients,
        doctors=args.doctors,
        nurses=args.nurses,
        triage_stations=args.triage_stations,
        lab_technicians=args.lab_technicians,
        arrival_interval=args.arrival_interval,
        seed=args.seed,
    )