import argparse

from common import load_event_log, ensure_output_dir


def main():
    parser = argparse.ArgumentParser(
        description="Analyze CareFlow patient pathways."
    )
    parser.add_argument(
        "--input",
        default="careflow_event_log.csv"
    )
    parser.add_argument(
        "--output-dir",
        default="outputs"
    )
    parser.add_argument(
        "--top-n",
        type=int,
        default=10
    )
    # Use parse_known_args to ignore Jupyter notebook's internal arguments
    args, _ = parser.parse_known_args()

    if args.top_n < 1:
        raise ValueError("--top-n must be at least 1.")

    output_dir = ensure_output_dir(args.output_dir)
    df, summary = load_event_log(args.input)

    case_paths = (
        df.groupby("case_id", sort=False)["activity"]
        .agg(list)
        .reset_index(name="activities")
    )

    case_paths["pathway"] = (
        case_paths["activities"]
        .apply(lambda sequence: " -> ".join(sequence))
    )

    case_paths["pathway_length"] = (
        case_paths["activities"].apply(len)
    )

    frequencies = (
        case_paths.groupby("pathway")
        .agg(
            case_count=("case_id", "nunique"),
            pathway_length=("pathway_length", "first")
        )
        .reset_index()
        .sort_values(
            ["case_count", "pathway_length"],
            ascending=[False, True]
        )
    )

    total_cases = int(case_paths["case_id"].nunique())

    frequencies["case_percent"] = (
        frequencies["case_count"] / total_cases * 100
    ).round(2)

    frequencies.to_csv(
        output_dir / "pathway_frequencies.csv",
        index=False
    )

    frequencies.head(args.top_n).to_csv(
        output_dir / "top_pathways.csv",
        index=False
    )

    print("Pathway analysis completed.")

    for key, value in summary.items():
        print(f"{key}: {value}")

    print("Distinct exact pathways:", len(frequencies))
    print(
        "All pathways:",
        (output_dir / "pathway_frequencies.csv").resolve()
    )
    print(
        "Top pathways:",
        (output_dir / "top_pathways.csv").resolve()
    )


if __name__ == "__main__":
    main()