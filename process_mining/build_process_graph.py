import argparse
import networkx as nx
import plotly.graph_objects as go
import pandas as pd
from pathlib import Path


def ensure_output_dir(dir_path):
    path = Path(dir_path)
    path.mkdir(parents=True, exist_ok=True)
    return path


def load_event_log(csv_path):
    df = pd.read_csv(csv_path)
    summary = {
        "Total Events": len(df),
        "Unique Cases": df["case_id"].nunique(),
        "Unique Activities": df["activity"].nunique()
    }
    return df, summary


def main():
    parser = argparse.ArgumentParser(
        description="Build the interactive CareFlow process graph."
    )
    parser.add_argument(
        "--input",
        default="careflow_event_log.csv"
    )
    parser.add_argument(
        "--output-dir",
        default="outputs"
    )
    parser.add_argument(
        "--min-count",
        type=int,
        default=1,
        help="Minimum transition frequency to include."
    )
    # Using parse_known_args in Jupyter notebooks to avoid conflicts with Colab arguments
    args, unknown = parser.parse_known_args()

    output_dir = ensure_output_dir(args.output_dir)
    df, summary = load_event_log(args.input)

    df["next_activity"] = (
        df.groupby("case_id")["activity"].shift(-1)
    )

    transitions = df[df["next_activity"].notna()]

    edges = (
        transitions.groupby(["activity", "next_activity"])
        .size()
        .reset_index(name="transition_count")
        .rename(columns={
            "activity": "source",
            "next_activity": "target"
        })
    )

    edges = edges[
        edges["transition_count"] >= args.min_count
    ].copy()

    if edges.empty:
        raise ValueError(
            "No transitions meet the minimum count. "
            "Try --min-count 1."
        )

    edges.to_csv(
        output_dir / "process_graph_edges.csv",
        index=False
    )

    nodes = (
        df.groupby("activity")["case_id"]
        .nunique()
        .reset_index(name="cases_with_activity")
    )

    nodes.to_csv(
        output_dir / "process_graph_nodes.csv",
        index=False
    )

    graph = nx.DiGraph()

    for row in nodes.itertuples(index=False):
        graph.add_node(
            row.activity,
            cases=int(row.cases_with_activity)
        )

    for row in edges.itertuples(index=False):
        graph.add_edge(
            row.source,
            row.target,
            weight=int(row.transition_count)
        )

    positions = nx.spring_layout(
        graph, seed=42, k=1.2
    )

    edge_x, edge_y = [], []
    annotations = []

    for source, target in graph.edges():
        x0, y0 = positions[source]
        x1, y1 = positions[target]

        edge_x.extend([x0, x1, None])
        edge_y.extend([y0, y1, None])

        annotations.append({
            "ax": x0,
            "ay": y0,
            "x": x1,
            "y": y1,
            "xref": "x",
            "yref": "y",
            "axref": "x",
            "ayref": "y",
            "showarrow": True,
            "arrowhead": 3,
            "arrowsize": 1,
            "arrowwidth": 1,
            "opacity": 0.65
        })

    edge_trace = go.Scatter(
        x=edge_x,
        y=edge_y,
        mode="lines",
        line={"width": 1.5},
        hoverinfo="none",
        name="Transitions"
    )

    node_x, node_y = [], []
    labels, hover_text, sizes = [], [], []

    max_cases = max(
        data["cases"]
        for _, data in graph.nodes(data=True)
    )

    for node, data in graph.nodes(data=True):
        x, y = positions[node]

        node_x.append(x)
        node_y.append(y)
        labels.append(node)

        hover_text.append(
            f"Activity: {node}<br>"
            f"Cases with activity: {data['cases']}"
        )

        sizes.append(
            14 + 18 * data["cases"] / max_cases
        )

    node_trace = go.Scatter(
        x=node_x,
        y=node_y,
        mode="markers+text",
        text=labels,
        textposition="top center",
        hovertext=hover_text,
        hoverinfo="text",
        marker={
            "size": sizes,
            "line": {"width": 1}
        },
        name="Activities"
    )

    fig = go.Figure(
        data=[edge_trace, node_trace]
    )

    fig.update_layout(
        title="CareFlow — Observed Activity Transition Graph",
        annotations=annotations,
        showlegend=False,
        hovermode="closest",
        margin={"l": 20, "r": 20, "t": 60, "b": 20},
        xaxis={"visible": False},
        yaxis={"visible": False},
        template="plotly_white"
    )

    html_file = (
        output_dir / "careflow_interactive_process_graph.html"
    )

    fig.write_html(
        str(html_file),
        include_plotlyjs="cdn"
    )

    print("Interactive graph created.")

    for key, value in summary.items():
        print(f"{key}: {value}")

    print("Nodes:", output_dir / "process_graph_nodes.csv")
    print("Edges:", output_dir / "process_graph_edges.csv")
    print("Interactive HTML:", html_file.resolve())


if __name__ == "__main__":
    main()