import argparse
from pathlib import Path
import pandas as pd


def ensure_output_dir(output_dir_path):
    path = Path(output_dir_path)
    path.mkdir(parents=True, exist_ok=True)
    return path


def load_event_log(file_path):
    # Load event log and parse the timestamp column
    df = pd.read_csv(file_path)
    df["timestamp"] = pd.to_datetime(df["timestamp"])

    summary = {
        "Total Rows": len(df),
        "Unique Cases": df["case_id"].nunique(),
        "Unique Activities": df["activity"].nunique()
    }
    return df, summary


def main():
    parser = argparse.ArgumentParser(
        description="Analyze CareFlow transition times."
    )
    parser.add_argument(
        "--input",
        default="careflow_event_log.csv"
    )
    parser.add_argument(
        "--output-dir",
        default="outputs"
    )
    # Using parse_known_args() instead of parse_args() to prevent errors when running in a Jupyter/Colab notebook environment
    args, unknown = parser.parse_known_args()

    output_dir = ensure_output_dir(args.output_dir)
    df, summary = load_event_log(args.input)

    df["next_activity"] = (
        df.groupby("case_id")["activity"].shift(-1)
    )

    df["next_timestamp"] = (
        df.groupby("case_id")["timestamp"].shift(-1)
    )

    transitions = df[
        df["next_activity"].notna()
    ].copy()

    transitions["elapsed_minutes"] = (
        (
            transitions["next_timestamp"]
            - transitions["timestamp"]
        ).dt.total_seconds() / 60
    )

    negative_count = int(
        (transitions["elapsed_minutes"] < 0).sum()
    )

    valid_times = transitions[
        transitions["elapsed_minutes"] >= 0
    ]

    transition_counts = (
        transitions.groupby(["activity", "next_activity"])
        .size()
        .reset_index(name="transition_count")
        .rename(columns={
            "activity": "from_activity",
            "next_activity": "to_activity"
        })
    )

    time_stats = (
        valid_times.groupby(["activity", "next_activity"])
        ["elapsed_minutes"]
        .agg(
            valid_time_count="count",
            average_minutes="mean",
            median_minutes="median",
            minimum_minutes="min",
            maximum_minutes="max"
        )
        .reset_index()
        .rename(columns={
            "activity": "from_activity",
            "next_activity": "to_activity"
        })
    )

    metrics = transition_counts.merge(
        time_stats,
        on=["from_activity", "to_activity"],
        how="left"
    )

    time_columns = [
        "average_minutes",
        "median_minutes",
        "minimum_minutes",
        "maximum_minutes"
    ]

    for column in time_columns:
        metrics[column] = metrics[column].round(2)

    metrics = metrics.sort_values(
        ["median_minutes", "transition_count"],
        ascending=[False, False],
        na_position="last"
    )

    metrics.to_csv(
        output_dir / "transition_metrics.csv",
        index=False
    )

    case_metrics = (
        df.groupby("case_id")
        .agg(
            event_count=("activity", "size"),
            unique_activities=("activity", "nunique"),
            first_event=("timestamp", "min"),
            last_event=("timestamp", "max")
        )
        .reset_index()
    )

    case_metrics["observed_duration_minutes"] = (
        (
            case_metrics["last_event"]
            - case_metrics["first_event"]
        ).dt.total_seconds() / 60
    ).round(2)

    case_metrics.to_csv(
        output_dir / "case_metrics.csv",
        index=False
    )

    print("Transition analysis completed.")

    for key, value in summary.items():
        print(f"{key}: {value}")

    print(
        "Negative intervals excluded from time statistics:",
        negative_count
    )
    print(
        "Transition metrics:",
        (output_dir / "transition_metrics.csv").resolve()
    )
    print(
        "Case metrics:",
        (output_dir / "case_metrics.csv").resolve()
    )

    print(
        "Note: elapsed time is not automatically clinical waiting time."
    )


if __name__ == "__main__":
    main()