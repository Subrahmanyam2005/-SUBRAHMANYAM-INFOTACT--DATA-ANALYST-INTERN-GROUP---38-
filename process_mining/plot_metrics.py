from pathlib import Path
import pandas as pd
import matplotlib.pyplot as plt

OUTPUT_DIR = Path("outputs")
INPUT_FILE = "/content/bottleneck_summary.csv"

df = pd.read_csv(INPUT_FILE)

# Keep transitions with enough cases for initial screening.
df = df[df["enough_cases_for_screening"] == True].copy()

if df.empty:
    print("No transitions meet the minimum case threshold.")
else:
    df = df.nlargest(10, "p90_minutes").sort_values("p90_minutes")

    labels = (
        df["from_activity"].astype(str)
        + " → "
        + df["to_activity"].astype(str)
    )

    plt.figure(figsize=(11, 6))
    plt.barh(labels, df["p90_minutes"])
    plt.xlabel("P90 elapsed time (minutes)")
    plt.ylabel("Activity transition")
    plt.title("CareFlow: Highest P90 Transition Times")
    plt.tight_layout()

    chart_path = OUTPUT_DIR / "bottleneck_p90_chart.png"
    plt.savefig(chart_path, dpi=160, bbox_inches="tight")
    plt.show()

    print(f"Chart saved to {chart_path}")