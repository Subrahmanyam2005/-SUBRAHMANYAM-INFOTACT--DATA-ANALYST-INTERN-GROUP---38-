import os
import pandas as pd

MANDATORY = [
    "Arrival",
    "Registration",
    "Triage",
    "Doctor Consultation",
    "Treatment",
    "Discharge"
]

OPTIONAL = ["Laboratory"]

def check_conformance(df):
    df = df.copy()

    df["timestamp"] = pd.to_datetime(
        df["timestamp"], errors="coerce", utc=True
    )

    df = df.dropna(
        subset=["case_id", "activity", "timestamp"]
    )

    df = df.sort_values(["case_id", "timestamp"])

    results = []

    for case_id, group in df.groupby("case_id"):
        actual = group["activity"].astype(str).tolist()

        # Remove consecutive duplicate activities for
        # the basic sequence comparison, but retain them
        # in the original event log for audit purposes.
        sequence = [
            activity for i, activity in enumerate(actual)
            if i == 0 or activity != actual[i - 1]
        ]

        missing = [
            activity for activity in MANDATORY
            if activity not in sequence
        ]

        positions = [
            sequence.index(activity)
            for activity in MANDATORY
            if activity in sequence
        ]

        wrong_order = positions != sorted(positions)

        unexpected = [
            activity for activity in sequence
            if activity not in MANDATORY
            and activity not in OPTIONAL
        ]

        compliant = (
            len(missing) == 0
            and not wrong_order
            and len(unexpected) == 0
        )

        deviations = []

        if missing:
            deviations.append("Missing: " + ", ".join(missing))

        if wrong_order:
            deviations.append("Mandatory activities out of order")

        if unexpected:
            deviations.append(
                "Unexpected: " + ", ".join(unexpected)
            )

        results.append({
            "case_id": case_id,
            "actual_pathway": " -> ".join(sequence),
            "missing_activities": ", ".join(missing),
            "unexpected_activities": ", ".join(unexpected),
            "wrong_order": wrong_order,
            "compliance_status": (
                "Compliant" if compliant else "Non-Compliant"
            ),
            "deviation_details": (
                "; ".join(deviations) if deviations else "None"
            )
        })

    return pd.DataFrame(results)


if __name__ == "__main__":
    # Use the actual available dataset file
    event_log = pd.read_csv("careflow_event_log.csv")

    result = check_conformance(event_log)

